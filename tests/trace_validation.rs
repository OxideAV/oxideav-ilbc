//! Structural bit-unpack validation against the per-fixture trace files
//! shipped under `docs/audio/ilbc/fixtures/<name>/trace.txt`.
//!
//! Each fixture directory ships a `trace.txt` that documents — frame by
//! frame — the structural fields the iLBC bitstream carries: `block_class`
//! (recorded as `start_subframe`), `position` (recorded as `state_first`),
//! the scale-factor / IFM index (`scale_factor_idx_ifm`), the empty-frame
//! indicator (`trailing_bit`), the split-VQ LSF indices (`LSF_DECODE
//! split_vq=[...]`), per-block CB and gain indices (`BLOCK_DECODE
//! block_idx=N cb_idx=[...] gain_idx=[...]`), plus the MSB of the first
//! 16 scalar start-state sample indices (`START_STATE_SAMPLE_PCM
//! idx[0:16]_msb=...`).
//!
//! The [`docs_corpus`](../docs_corpus/index.html) driver scores decoder
//! *PCM* against a reference WAV — that's a tail-end fidelity check that
//! catches CELP-pipeline drift but cannot distinguish "we read the
//! bitstream wrong" from "we read it right and synthesised a slightly
//! different waveform". This driver isolates the *bit layout*: every
//! frame's [`bitreader::parse_frame`] output is compared field-by-field
//! against the trace generator's structural emission. If a future RFC
//! 3951 §3.8 / Table 3.2 audit changes the bit-class layout, this driver
//! red-lights immediately on a per-fixture basis without waiting for
//! downstream PSNR to regress.
//!
//! All trace files were generated by the cleanroom docs collaborator
//! per `docs/audio/ilbc/ilbc-fixtures-and-traces.md`. The driver reads
//! the trace as a structured text artefact only — there is no encoder /
//! decoder under `docs/` and the trace is purely declarative.

use std::fs;
use std::path::PathBuf;

use oxideav_ilbc::bitreader::{parse_frame, FrameParams};
use oxideav_ilbc::{FrameMode, FRAME_BYTES_20MS, FRAME_BYTES_30MS};

// ---------------------------------------------------------------------------
// Trace records
// ---------------------------------------------------------------------------

/// Per-block expectation from one `BLOCK_DECODE` line in a trace file.
#[derive(Clone, Debug, PartialEq, Eq)]
struct BlockExpect {
    block_idx: usize,
    cb_idx: [u16; 3],
    gain_idx: [u8; 3],
}

/// One `FRAME #NNNN` block's worth of structural fields from a trace.
#[derive(Clone, Debug)]
struct FrameExpect {
    frame_no: usize,
    mode: FrameMode,
    byte_size: usize,
    start_subframe: u8,
    state_first: u8,
    scale_factor_idx_ifm: u8,
    trailing_bit: u8,
    /// Split-VQ LSF indices (1 row × 3 entries for 20 ms, 2 × 3 for 30 ms).
    lsf_split_vq: Vec<[u16; 3]>,
    /// MSB (bit 2) of `state_samples[0..16]`, as a 16-char bitstring.
    state_first16_msb: String,
    blocks: Vec<BlockExpect>,
}

/// Parse one `trace.txt` into the list of per-frame structural records.
///
/// A `trace.txt` may carry MORE than one stream of frames concatenated
/// (e.g. the `transition-mid-stream` fixture documents `part_a` and
/// `part_b` back-to-back). Each stream restarts at `FRAME #0000` and is
/// prefaced with a `# iLBC trace for <input file>` comment line. The
/// returned list is the concatenation of all streams; the caller pairs
/// the records up against the matching input file.
fn parse_trace_streams(text: &str) -> Vec<Vec<FrameExpect>> {
    let mut streams: Vec<Vec<FrameExpect>> = Vec::new();
    let mut current: Vec<FrameExpect> = Vec::new();
    let mut cur: Option<FrameExpect> = None;

    for raw_line in text.lines() {
        let line = raw_line.trim_end();
        // Stream boundary: `# iLBC trace for <file>` resets the stream
        // context. The first trace line in the file matches this so we
        // emit any pending stream before starting the new one.
        if line.starts_with("# iLBC trace for ") {
            if let Some(fe) = cur.take() {
                current.push(fe);
            }
            if !current.is_empty() {
                streams.push(std::mem::take(&mut current));
            }
            continue;
        }
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // `FRAME #NNNN mode=... byte_size=... start_subframe=...
        //   state_first=... scale_factor_idx_ifm=... trailing_bit=...`
        if let Some(rest) = line.strip_prefix("FRAME #") {
            if let Some(fe) = cur.take() {
                current.push(fe);
            }
            let frame_no = parse_first_int::<usize>(rest);
            let mode = match field_str(line, "mode") {
                Some("20ms") => FrameMode::Ms20,
                Some("30ms") => FrameMode::Ms30,
                other => panic!("unrecognised FRAME mode field: {other:?}"),
            };
            cur = Some(FrameExpect {
                frame_no,
                mode,
                byte_size: field_int(line, "byte_size").unwrap_or(0) as usize,
                start_subframe: field_int(line, "start_subframe").unwrap_or(0) as u8,
                state_first: field_int(line, "state_first").unwrap_or(0) as u8,
                scale_factor_idx_ifm: field_int(line, "scale_factor_idx_ifm").unwrap_or(0) as u8,
                trailing_bit: field_int(line, "trailing_bit").unwrap_or(0) as u8,
                lsf_split_vq: Vec::new(),
                state_first16_msb: String::new(),
                blocks: Vec::new(),
            });
            continue;
        }
        let body = line.trim_start();
        if let Some(rest) = body.strip_prefix("LSF_DECODE split_vq=") {
            // `[ a  b  c]` or `[ a  b  c   d  e  f]`.
            let nums = parse_bracketed_u16_list(rest);
            assert!(
                nums.len() % 3 == 0 && !nums.is_empty(),
                "LSF_DECODE split_vq length not a positive multiple of 3"
            );
            let mut rows = Vec::with_capacity(nums.len() / 3);
            for chunk in nums.chunks_exact(3) {
                rows.push([chunk[0], chunk[1], chunk[2]]);
            }
            if let Some(fe) = cur.as_mut() {
                fe.lsf_split_vq = rows;
            }
        } else if let Some(rest) = body.strip_prefix("START_STATE_SAMPLE_PCM idx[0:16]_msb=") {
            let bits = rest.trim().to_string();
            if let Some(fe) = cur.as_mut() {
                fe.state_first16_msb = bits;
            }
        } else if let Some(rest) = body.strip_prefix("BLOCK_DECODE ") {
            // `block_idx=N cb_idx=[a b c] gain_idx=[d e f]`.
            let block_idx = field_int(rest, "block_idx").unwrap_or(0) as usize;
            let cb_vec = field_bracketed_list(rest, "cb_idx");
            let g_vec = field_bracketed_list(rest, "gain_idx");
            assert_eq!(cb_vec.len(), 3, "BLOCK_DECODE cb_idx length != 3");
            assert_eq!(g_vec.len(), 3, "BLOCK_DECODE gain_idx length != 3");
            if let Some(fe) = cur.as_mut() {
                fe.blocks.push(BlockExpect {
                    block_idx,
                    cb_idx: [cb_vec[0], cb_vec[1], cb_vec[2]],
                    gain_idx: [g_vec[0] as u8, g_vec[1] as u8, g_vec[2] as u8],
                });
            }
        }
        // Everything else (CB_VECTOR_USE detail, COMFORT_NOISE_HINT...)
        // is informational and not asserted here.
    }
    if let Some(fe) = cur.take() {
        current.push(fe);
    }
    if !current.is_empty() {
        streams.push(current);
    }
    streams
}

// --- text helpers (no regex; trace format is whitespace-delimited) ---

fn parse_first_int<T: std::str::FromStr>(s: &str) -> T
where
    <T as std::str::FromStr>::Err: std::fmt::Debug,
{
    let mut buf = String::new();
    for c in s.chars() {
        if c.is_ascii_digit() {
            buf.push(c);
        } else if !buf.is_empty() {
            break;
        }
    }
    buf.parse().expect("digit run parses as integer")
}

/// Look up `key=value` (value is a bare integer; the trace generator
/// right-pads short integers with leading whitespace for column
/// alignment, e.g. `scale_factor_idx_ifm= 0`).
fn field_int(line: &str, key: &str) -> Option<i64> {
    let needle = format!("{key}=");
    let idx = line.find(&needle)?;
    let after = &line[idx + needle.len()..];
    let mut buf = String::new();
    let mut started = false;
    for c in after.chars() {
        if c.is_ascii_digit() || (c == '-' && !started) {
            buf.push(c);
            started = true;
        } else if started {
            break;
        }
        // Pre-digit whitespace inside the field is part of the
        // alignment padding; keep scanning.
    }
    buf.parse::<i64>().ok()
}

fn field_str<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let needle = format!("{key}=");
    let idx = line.find(&needle)?;
    let after = &line[idx + needle.len()..];
    let end = after
        .find(|c: char| c.is_whitespace())
        .unwrap_or(after.len());
    Some(&after[..end])
}

/// Parse `[a  b  c]` after stripping the lead-in `key=`. Used for
/// `BLOCK_DECODE cb_idx=[..]` / `gain_idx=[..]`. The opening `[` may
/// be either immediately after `=` or preceded by whitespace; numbers
/// inside are space-separated and may have leading spaces (e.g. `[ 15
/// 118  13]`).
fn field_bracketed_list(line: &str, key: &str) -> Vec<u16> {
    let needle = format!("{key}=[");
    let idx = line.find(&needle).expect("key present");
    let after_open = &line[idx + needle.len()..];
    let close = after_open.find(']').expect("matching close bracket");
    parse_bracketed_body_u16(&after_open[..close])
}

/// `parse_bracketed_u16_list("[ a  b  c] tail=...")` → `[a, b, c]`.
/// Accepts trailing text after the closing `]` and clips at it.
fn parse_bracketed_u16_list(s: &str) -> Vec<u16> {
    let s = s.trim_start();
    let s = s.strip_prefix('[').unwrap_or(s);
    let close = s.find(']').unwrap_or(s.len());
    parse_bracketed_body_u16(&s[..close])
}

fn parse_bracketed_body_u16(body: &str) -> Vec<u16> {
    body.split_whitespace()
        .map(|tok| tok.parse::<u16>().expect("u16 inside bracket list"))
        .collect()
}

