fn fixture_dir(name: &str) -> PathBuf {
    PathBuf::from("../../docs/audio/ilbc/fixtures").join(name)
}

/// Slice a storage-format `.lbc` (with `#!iLBC{20,30}\n` magic) into
/// per-frame payloads via the public `oxideav_ilbc::storage` parser.
fn split_storage_format(input: &[u8]) -> (FrameMode, Vec<Vec<u8>>) {
    let sf = oxideav_ilbc::storage::parse(input).expect("storage-format parse");
    (sf.mode, sf.frames().map(|f| f.to_vec()).collect())
}

fn split_raw(input: &[u8], mode: FrameMode) -> Vec<Vec<u8>> {
    let fs = match mode {
        FrameMode::Ms20 => FRAME_BYTES_20MS,
        FrameMode::Ms30 => FRAME_BYTES_30MS,
    };
    assert_eq!(
        input.len() % fs,
        0,
        "raw input length not multiple of frame size"
    );
    input.chunks_exact(fs).map(|c| c.to_vec()).collect()
}

/// Slice an RTP-style buffer: each frame prefixed with a big-endian
/// `uint16` length.
fn split_rtp_style(input: &[u8], mode: FrameMode) -> Vec<Vec<u8>> {
    let fs = match mode {
        FrameMode::Ms20 => FRAME_BYTES_20MS,
        FrameMode::Ms30 => FRAME_BYTES_30MS,
    };
    let mut off = 0usize;
    let mut frames = Vec::new();
    while off + 2 <= input.len() {
        let len = u16::from_be_bytes([input[off], input[off + 1]]) as usize;
        off += 2;
        assert_eq!(len, fs, "rtp-style frame length mismatch");
        assert!(off + len <= input.len(), "rtp-style frame truncated");
        frames.push(input[off..off + len].to_vec());
        off += len;
    }
    assert_eq!(off, input.len(), "rtp-style trailing bytes");
    frames
}

/// Skip a fixture cleanly when the docs/ submodule is not checked out
/// (e.g. in a downstream CI rig that vendors the crate without docs).
fn read_or_skip(path: PathBuf, what: &str) -> Option<Vec<u8>> {
    match fs::read(&path) {
        Ok(b) => Some(b),
        Err(e) => {
            eprintln!("skip {what} ({}): {e}", path.display());
            None
        }
    }
}

/// Validate one frame's parsed bitreader output against the trace.
fn check_frame(parsed: &FrameParams, expect: &FrameExpect, ctx: &str) {
    assert_eq!(
        parsed.mode, expect.mode,
        "{ctx}: mode mismatch (parsed {:?}, expected {:?})",
        parsed.mode, expect.mode
    );
    assert_eq!(
        parsed.block_class, expect.start_subframe,
        "{ctx}: block_class (`start_subframe`) mismatch",
    );
    assert_eq!(
        parsed.position, expect.state_first,
        "{ctx}: position (`state_first`) mismatch"
    );
    assert_eq!(
        parsed.scale_idx, expect.scale_factor_idx_ifm,
        "{ctx}: scale_idx (`scale_factor_idx_ifm`) mismatch"
    );
    assert_eq!(
        parsed.empty_flag,
        expect.trailing_bit != 0,
        "{ctx}: empty_flag (`trailing_bit`) mismatch"
    );
    // Byte size is a property of the mode; cross-check.
    let want_bytes = match expect.mode {
        FrameMode::Ms20 => FRAME_BYTES_20MS,
        FrameMode::Ms30 => FRAME_BYTES_30MS,
    };
    assert_eq!(
        expect.byte_size, want_bytes,
        "{ctx}: trace byte_size disagrees with FrameMode bytes"
    );
    // LSF split-VQ.
    assert_eq!(
        parsed.lsf_idx.len(),
        expect.lsf_split_vq.len(),
        "{ctx}: lsf vector count mismatch"
    );
    for (k, (got, want)) in parsed
        .lsf_idx
        .iter()
        .zip(expect.lsf_split_vq.iter())
        .enumerate()
    {
        assert_eq!(got, want, "{ctx}: lsf vector #{k} mismatch");
    }
    // The trace generator's `START_STATE_SAMPLE_PCM idx[0:16]_msb` field
    // encodes an encoder-side state-sample sign in a layout that is not
    // directly reconstructable from our [`FrameParams::state_samples`]
    // bitstream-side scalar indices (the RFC 3951 §5.3 state encoder
    // applies an all-pass phase compensator + log-scale mapping before
    // emitting the 3-bit indices). The trace text records 57 / 58 indices
    // but only the first 16 MSBs as an `idx[0:16]_msb` digest. Validating
    // this digest against `state_samples` is therefore not a clean
    // bit-layout cross-check; the indices themselves are still consumed
    // implicitly through the PSNR-floor gates in `docs_corpus.rs`. We
    // verify only that the trace digest has the documented 16-bit width.
    if !expect.state_first16_msb.is_empty() {
        assert_eq!(
            expect.state_first16_msb.len(),
            16,
            "{ctx}: START_STATE_SAMPLE_PCM idx[0:16]_msb width"
        );
        assert!(
            expect
                .state_first16_msb
                .chars()
                .all(|c| c == '0' || c == '1'),
            "{ctx}: START_STATE_SAMPLE_PCM idx[0:16]_msb non-bit chars"
        );
        assert!(
            parsed.state_samples.len() >= 16,
            "{ctx}: parsed state_samples shorter than the 16-MSB trace digest"
        );
    }
    // Block-decode cross-checks: the trace lists one `BLOCK_DECODE`
    // record per emitted excitation block (the boundary block plus
    // every codebook sub-block), in the encoder/decoder *processing*
    // order. Our bitreader emits the same blocks in the *wire* order
    // dictated by Table 3.2 — boundary first, then sub-blocks 1..N in
    // payload order. The two orders differ when `start_idx` ≠ 1 (the
    // encoder walks backward from `start-1` then forward from
    // `start+1`), so a positional `cb_idx[k]==want[k]` cross-check is
    // not always sound. What IS sound regardless of ordering:
    //
    //   * the block COUNT (1 boundary + N sub-blocks == trace's
    //     BLOCK_DECODE count for the frame);
    //   * the MULTISET of `(cb_idx, gain_idx)` tuples — every block
    //     emitted on the wire appears exactly once in the trace's
    //     processing-order list, and vice versa, so the sorted
    //     tuple-lists must match.
    //
    // The multiset check still catches a corrupted bit-class width
    // (every wrong width shifts one or more cb / gain indices into a
    // value the trace doesn't carry) without depending on the
    // wire-vs-processing ordering convention.
    let total_blocks = 1 + parsed.sub_blocks.len();
    assert_eq!(
        expect.blocks.len(),
        total_blocks,
        "{ctx}: block count mismatch (parsed {} boundary+sub_blocks, trace {})",
        total_blocks,
        expect.blocks.len()
    );
    for (k, want) in expect.blocks.iter().enumerate() {
        assert_eq!(
            want.block_idx, k,
            "{ctx}: trace block_idx is not monotone-from-zero"
        );
    }
    let mut got_tuples: Vec<([u16; 3], [u8; 3])> = Vec::with_capacity(total_blocks);
    got_tuples.push((parsed.boundary.cb_idx, parsed.boundary.gain_idx));
    for sb in &parsed.sub_blocks {
        got_tuples.push((sb.cb_idx, sb.gain_idx));
    }
    let mut want_tuples: Vec<([u16; 3], [u8; 3])> = expect
        .blocks
        .iter()
        .map(|b| (b.cb_idx, b.gain_idx))
        .collect();
    got_tuples.sort();
    want_tuples.sort();
    assert_eq!(
        got_tuples, want_tuples,
        "{ctx}: BLOCK_DECODE multiset mismatch (sorted (cb_idx, gain_idx) tuples)"
    );
}

/// Drive one storage-format fixture: parse the trace, parse the `.lbc`
/// payload, walk frames in lock-step and assert structural equality.
fn drive_storage_format(name: &str, input_file: &str) {
    let dir = fixture_dir(name);
    let input = match read_or_skip(dir.join(input_file), &format!("{name}/{input_file}")) {
        Some(v) => v,
        None => return,
    };
    let trace_bytes = match read_or_skip(dir.join("trace.txt"), &format!("{name}/trace.txt")) {
        Some(v) => v,
        None => return,
    };
    let trace = String::from_utf8(trace_bytes).expect("trace.txt is utf-8");
    let streams = parse_trace_streams(&trace);
    assert!(!streams.is_empty(), "{name}: trace produced no streams");
    // Find the stream that names this input file in its header.
    let header_needle = format!("# iLBC trace for {input_file}");
    let stream_idx = trace
        .lines()
        .enumerate()
        .filter(|(_, l)| l.starts_with("# iLBC trace for "))
        .position(|(_, l)| l.trim() == header_needle)
        .unwrap_or(0);
    let expects = streams.get(stream_idx).expect("stream index in range");
    let (mode, frames) = split_storage_format(&input);
    assert_eq!(
        frames.len(),
        expects.len(),
        "{name}/{input_file}: frame-count mismatch (decoded {}, trace {})",
        frames.len(),
        expects.len()
    );
    for (i, (frame, expect)) in frames.iter().zip(expects.iter()).enumerate() {
        let ctx = format!("{name}/{input_file} frame #{i:04}");
        assert_eq!(expect.frame_no, i, "{ctx}: trace frame_no out of order");
        assert_eq!(mode, expect.mode, "{ctx}: stream mode disagrees with trace");
        let parsed = parse_frame(frame)
            .unwrap_or_else(|e| panic!("{ctx}: bitreader::parse_frame failed: {e}"));
        check_frame(&parsed, expect, &ctx);
    }
}

/// Drive a raw or RTP-style view of the containerless fixture.
fn drive_raw(name: &str, input_file: &str, mode: FrameMode) {
    let dir = fixture_dir(name);
    let input = match read_or_skip(dir.join(input_file), &format!("{name}/{input_file}")) {
        Some(v) => v,
        None => return,
    };
    let trace_bytes = match read_or_skip(dir.join("trace.txt"), &format!("{name}/trace.txt")) {
        Some(v) => v,
        None => return,
    };
    let trace = String::from_utf8(trace_bytes).expect("trace.txt is utf-8");
    // The containerless-vs-rtp-style-pair fixture documents its trace
    // against the storage-format view of the bitstream; the raw and
    // RTP-style views carry the SAME frame bytes. Comparing our
    // bit-unpack of either alternate view against that trace
    // simultaneously validates (a) our carriage parser splits the
    // frames out byte-identically and (b) the bit layout is shared.
    let streams = parse_trace_streams(&trace);
    assert!(!streams.is_empty(), "{name}: trace produced no streams");
    let expects = &streams[0];

    let frames = if input_file.ends_with(".bin") && input_file.contains("rtp") {
        split_rtp_style(&input, mode)
    } else {
        split_raw(&input, mode)
    };
    assert_eq!(
        frames.len(),
        expects.len(),
        "{name}/{input_file}: frame-count mismatch (decoded {}, trace {})",
        frames.len(),
        expects.len()
    );
    for (i, (frame, expect)) in frames.iter().zip(expects.iter()).enumerate() {
        let ctx = format!("{name}/{input_file} frame #{i:04}");
        let parsed = parse_frame(frame)
            .unwrap_or_else(|e| panic!("{ctx}: bitreader::parse_frame failed: {e}"));
        assert_eq!(mode, expect.mode, "{ctx}: caller mode disagrees with trace");
        check_frame(&parsed, expect, &ctx);
    }
}

